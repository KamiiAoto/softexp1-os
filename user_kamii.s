PUTCHAR:
	movem.l	%d0-%d3, -(%sp)
	move.b 	%d1, CHAR_BUF
PUTCHAR_LOOP:
	moveq.l #1, %d3
	move.l	#SYSCALL_NUM_PUTSTRING, %d0
	move.l	#0, %d1                 | ch = 0
	move.l	#CHAR_BUF,%d2                | p  = #BUF
	trap	#0
	cmpi.l	#1, %d0
	beq 	PUTCHAR_FIN
	bra		PUTCHAR_LOOP
PUTCHAR_FIN:
	movem.l	(%sp)+, %d0-%d3
	rts

***************************************************************
** PUTS : 0 で終わる文字列を表示する
**   【入力】%A0 = 文字列の先頭
**   【戻り値】なし（レジスタはすべて保存する）
**   【ヒント】0 が出てくるまで 1 文字ずつ PUTCHAR を呼ぶ．
***************************************************************
PUTS:
	movem.l	%d1/%a0, -(%sp)

PUTS_LOOP:
	move.b	(%a0)+, %d1
	cmpi.b	#0, %d1
	beq		PUTS_FIN
	jsr		PUTCHAR
	bra		PUTS_LOOP

PUTS_FIN:
	movem.l	(%sp)+, %d1/%a0
	rts

