***************************************************************
* Step 4 統合動作テスト
* a～p を各16文字、計256文字送信する
***************************************************************

* 各担当のプログラムを組み込む
.include "os_defs.s"
.include "os_init_step4.s"
.include "os_interface.s"
.include "os_queue.s"
.include "os_uart.s"
.include "os_timer.s"

.section .text
.even

***************************************************************
* メインプログラム
***************************************************************
MAIN:
    * カウンタD2を0に初期化
    move.l #0, %D2

***************************************************************
* 256文字を送信キューに格納
***************************************************************
STEP4_FILL:

    * D2を16で割った商をD3に入れる
    * D2=0～15   → D3=0
    * D2=16～31  → D3=1
    * ...
    * D2=240～255 → D3=15

    move.l %D2, %D3
    lsr.l #4, %D3

    * 0～15をASCIIコード'a'～'p'に変換
    addi.b #0x61, %D3

    * INQで送信キュー1に文字を格納
    move.l #1, %D0
    move.b %D3, %D1
    jsr INQ

    * 格納に失敗した場合
    tst.l %D0
    beq STEP4_ERROR

    * カウンタを1増やす
    addq.l #1, %D2

    * 256文字格納したか確認
    cmpi.l #256, %D2
    bne STEP4_FILL

***************************************************************
* 256文字の格納完了
* ここから送信割り込みを許可
***************************************************************

    * UART1の割り込みを許可
    move.l #0x00ff3ffb, IMR

    * UART1の送信割り込みを許可
    move.w #0xe104, USTCNT1

    * CPUの割り込みマスクレベルを0に
    move.w #0x2000, %SR

***************************************************************
* 送信は割り込み処理に任せる
***************************************************************
STEP4_IDLE:
    bra STEP4_IDLE

***************************************************************
* キューへの格納失敗時
***************************************************************
STEP4_ERROR:
    bra STEP4_ERROR
