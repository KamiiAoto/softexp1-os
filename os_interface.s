***************************************************************
** UART1_INTERRUPT : 送受信割り込み用のハードウェア割り込みインタフェース
**   (Step 4: 3.8.2 節 p.34 の (1)(2),  Step 6: 3.10.3 節 p.39 の (3)〜(6))
**   レベル 4 (UART1) のベクタに登録する．
**   【注意】UTX1 / URX1 は一度読むと更新されるので，別レジスタにコピーして使う．
***************************************************************
UART1_INTERRUPT:

    * D0とD1の元の値を保存
    move.l %D0, -(%SP)
    move.l %D1, -(%SP)

    * UTX1の内容を取得
    move.w UTX1, %D0

    * bit15だけを取り出す
    andi.w #0x8000, %D0

    * bit15が0なら送信処理を行わない
    beq NOT_SEND

    * INTERPUTにUART1のチャネル番号0を渡す
    move.l #0x0000, %D1

    * 送信担当のINTERPUTを呼び出す
    jsr INTERPUT

NOT_SEND:

    * D1とD0を元の値に復元
    move.l (%SP)+, %D1
    move.l (%SP)+, %D0

    * 割り込み前の処理に復帰
    rte
***************************************************************
** TIMER1_INTERRUPT : タイマ用のハードウェア割り込みインタフェース
**   (Step 7: 3.11.2 節 p.42 の (1)〜(3))
**   レベル 6 (タイマ 1) のベクタに登録する．
***************************************************************
TIMER1_INTERRUPT:
	movem.l	%d0-%d7/%a0-%a6,-(%sp)
	move.w	TSTAT1, %d0
	btst	#0, %d0
	beq		TIMER1_EXIT
	move.w	#0, TSTAT1
	jsr	CALL_RP
TIMER1_EXIT:
	movem.l	(%sp)+,%d0-%d7/%a0-%a6
	rte

