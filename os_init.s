**   エントリファイルでは os_defs.s の直後に .include すること．
**   boot が .text の先頭 = 0x400 番地に置かれる必要がある (付録 A.1.1.3)．
**   以下の boot はテキスト 3.5 節 (p.29-30) のコードそのまま．
**   Step が進むごとに TODO を埋めていく．
