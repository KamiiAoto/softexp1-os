***************************************************************
** test_step0_queue.s : キューの正常動作の確認 (Step 0, テキスト 3.4.3 節 p.26-28)
**   担当: 受信・送信担当
**
**   エミュレータ (m68k-emu / BSVC) で実行する．
**   BSVC には内蔵デバイスが無いので，os_init.s の boot は使わない
**   (デバイスレジスタに触るとバスエラーになる)．ここに専用の start を書く．
**
**   アセンブル: m68k-as -t 400 test_step0_queue.s
**   実行: m68k-emu で .abs を読み込み，PC = 0x400 にして実行．
**         領域のアドレスは .LIS ファイルで調べる．
***************************************************************
	.include "os_defs.s"

* もし os_defs.s に以下のオフセット定義が無い場合はコメントを外してください
* .equ	TOP,	0
* .equ	BOTTOM,	4
* .equ	OUT,	8
* .equ	IN,	12
* .equ	S,	16

.section .bss
.even
TEST_STK:
	.ds.b	0x1000
.even
TEST_STK_TOP:

***************************************************************
** 手順2: テスト用の4つの領域 (キューサイズ256以上 = 300要素分確保)
**   ※1回のテストごとに先頭へ戻す方式でも、連続して記録する方式でも確認できるよう
**     各ステップ開始時に %A0〜%A3 を再初期化しています。
**     ブレークポイントを置いて各ステップ終了時にメモリを確認してください。
***************************************************************
.even
INQ_RET_BUF:
	.ds.l	300		| %A1: INQ の戻り値 (0 or 1) 格納領域 (4byte × 300)
OUTQ_DATA_BUF:
	.ds.b	300		| %A2: OUTQ で読み込んだデータ格納領域 (1byte × 300)
.even
OUTQ_RET_BUF:
	.ds.l	300		| %A3: OUTQ の戻り値 (0 or 1) 格納領域 (4byte × 300)


.section .text
.even
start:
	move.w	#0x2700, %SR		| スーパーバイザモード (INQ/OUTQ は %SR を操作する)
	lea.l	TEST_STK_TOP, %SP
	jsr	QUEUE_INIT

	** ============================================================
	** 手順6の準備: キューのメモリ領域の前後に適当なデータを書き込む
	**   BF0_START の直前 4バイト と BF1_END の直後(Q0_INFOの手前) 等に
	**   エミュレータから手動で書き込むか、以下のようにプログラムで書き込む。
	** ============================================================
	lea.l	BF0_START, %a4
	move.b	#0xAA, -1(%a4)		| BF0_START の1バイト前に 0xAA を書き込む

	** ============================================================
	** 【キュー0 (no = 0) のテスト】 (手順3 & 手順4)
	** ============================================================

	** ------------------------------------------------------------
	** 手順3(a) [no=0]: INQ を 128 回行う
	** ------------------------------------------------------------
	lea.l	INQ_DATA_BUF, %a0	| %A0: INQで読み込むデータの先頭アドレス
	lea.l	INQ_RET_BUF, %a1	| %A1: INQの戻り値を格納する先頭アドレス
	move.l	#128-1, %d2		| ループカウンタ (dbra用に 128-1 = 127)
STEP3_Q0_INQ_LOOP:
	move.l	#0, %d0			| キュー番号 no = 0
	move.b	(%a0)+, %d1		| (注意1) 書き込むデータを与える
	jsr	INQ
	move.l	%d0, (%a1)+		| (注意2) 戻り値(0 or 1)を格納
	dbra	%d2, STEP3_Q0_INQ_LOOP

STEP3_Q0_INQ_DONE:
	* 【確認ポイント1】ここにブレークポイントを置くと手順3(a)を確認できます
	*   - BF0_START から 128個のデータが入っているか
	*   - INQ_RET_BUF から 128個の .L がすべて 1 か

	** ------------------------------------------------------------
	** 手順3(b) [no=0]: OUTQ を 129 回行う
	** ------------------------------------------------------------
	lea.l	OUTQ_DATA_BUF, %a2	| %A2: OUTQで読み込んだデータを格納する先頭アドレス
	lea.l	OUTQ_RET_BUF, %a3	| %A3: OUTQの戻り値を格納する先頭アドレス
	move.l	#129-1, %d2		| ループカウンタ (129回)
STEP3_Q0_OUTQ_LOOP:
	move.l	#0, %d0			| キュー番号 no = 0
	move.b	#0xFF, %d1		| ダミー値でクリアしておく
	jsr	OUTQ
	move.b	%d1, (%a2)+		| (注意1) 読み込んだデータを格納
	move.l	%d0, (%a3)+		| (注意2) 戻り値(0 or 1)を格納
	dbra	%d2, STEP3_Q0_OUTQ_LOOP

STEP3_Q0_OUTQ_DONE:
	* 【確認ポイント2】ここにブレークポイントを置くと手順3(b)を確認できます
	*   - OUTQ_DATA_BUF に 128個、入力と同じ順番でデータが出力されているか
	*   - OUTQ_RET_BUF の 128個目までが 1 で、129個目が 0 (失敗) になっているか

	** ------------------------------------------------------------
	** 手順4(a) [no=0]: INQ を 257 回行う (ポインタがラップアラウンドするかも確認)
	** ------------------------------------------------------------
	lea.l	INQ_DATA_BUF, %a0
	lea.l	INQ_RET_BUF, %a1
	move.l	#257-1, %d2		| ループカウンタ (257回)
STEP4_Q0_INQ_LOOP:
	move.l	#0, %d0			| キュー番号 no = 0
	move.b	(%a0)+, %d1
	jsr	INQ
	move.l	%d0, (%a1)+
	dbra	%d2, STEP4_Q0_INQ_LOOP

STEP4_Q0_INQ_DONE:
	* 【確認ポイント3】ここにブレークポイントを置くと手順4(a)を確認できます
	*   - 256回目まで成功(INQ_RET_BUFが1)、257回目が失敗(0)となっているか
	*   - BF0_START〜BF0_END に 256個のデータが保存されているか

	** ------------------------------------------------------------
	** 手順4(b) [no=0]: OUTQ を 257 回行う
	** ------------------------------------------------------------
	lea.l	OUTQ_DATA_BUF, %a2
	lea.l	OUTQ_RET_BUF, %a3
	move.l	#257-1, %d2		| ループカウンタ (257回)
STEP4_Q0_OUTQ_LOOP:
	move.l	#0, %d0			| キュー番号 no = 0
	move.b	#0xFF, %d1
	jsr	OUTQ
	move.b	%d1, (%a2)+
	move.l	%d0, (%a3)+
	dbra	%d2, STEP4_Q0_OUTQ_LOOP

STEP4_Q0_OUTQ_DONE:
	* 【確認ポイント4】ここにブレークポイントを置くと手順4(b)を確認できます
	*   - OUTQ_DATA_BUF に 256個、入力と同じ順番でデータが出力されているか
	*   - OUTQ_RET_BUF の 256個目までが 1 で、257個目が 0 (失敗) になっているか


	** ============================================================
	** 手順5: 【キュー1 (no = 1) のテスト】 (手順3 & 手順4 と同様の確認)
	** ============================================================

	** ------------------------------------------------------------
	** 手順3(a) [no=1]: INQ を 128 回行う
	** ------------------------------------------------------------
	lea.l	INQ_DATA_BUF, %a0
	lea.l	INQ_RET_BUF, %a1
	move.l	#128-1, %d2
STEP3_Q1_INQ_LOOP:
	move.l	#1, %d0			| キュー番号 no = 1
	move.b	(%a0)+, %d1
	jsr	INQ
	move.l	%d0, (%a1)+
	dbra	%d2, STEP3_Q1_INQ_LOOP

STEP3_Q1_INQ_DONE:
	* 【確認ポイント5】キュー1の手順3(a)完了時点

	** ------------------------------------------------------------
	** 手順3(b) [no=1]: OUTQ を 129 回行う
	** ------------------------------------------------------------
	lea.l	OUTQ_DATA_BUF, %a2
	lea.l	OUTQ_RET_BUF, %a3
	move.l	#129-1, %d2
STEP3_Q1_OUTQ_LOOP:
	move.l	#1, %d0			| キュー番号 no = 1
	move.b	#0xFF, %d1
	jsr	OUTQ
	move.b	%d1, (%a2)+
	move.l	%d0, (%a3)+
	dbra	%d2, STEP3_Q1_OUTQ_LOOP

STEP3_Q1_OUTQ_DONE:
	* 【確認ポイント6】キュー1の手順3(b)完了時点

	** ------------------------------------------------------------
	** 手順4(a) [no=1]: INQ を 257 回行う
	** ------------------------------------------------------------
	lea.l	INQ_DATA_BUF, %a0
	lea.l	INQ_RET_BUF, %a1
	move.l	#257-1, %d2
STEP4_Q1_INQ_LOOP:
	move.l	#1, %d0			| キュー番号 no = 1
	move.b	(%a0)+, %d1
	jsr	INQ
	move.l	%d0, (%a1)+
	dbra	%d2, STEP4_Q1_INQ_LOOP

STEP4_Q1_INQ_DONE:
	* 【確認ポイント7】キュー1の手順4(a)完了時点

	** ------------------------------------------------------------
	** 手順4(b) [no=1]: OUTQ を 257 回行う
	** ------------------------------------------------------------
	lea.l	OUTQ_DATA_BUF, %a2
	lea.l	OUTQ_RET_BUF, %a3
	move.l	#257-1, %d2
STEP4_Q1_OUTQ_LOOP:
	move.l	#1, %d0			| キュー番号 no = 1
	move.b	#0xFF, %d1
	jsr	OUTQ
	move.b	%d1, (%a2)+
	move.l	%d0, (%a3)+
	dbra	%d2, STEP4_Q1_OUTQ_LOOP

STEP4_Q1_OUTQ_DONE:
	* 【確認ポイント8】キュー1の手順4(b)完了時点 & 手順6(領域外チェック)
	*   - BF0_START の1バイト前 (0xAA) や Q0_INFO (top0等) が破壊されていないか確認

	stop	#0x2700

	.include "os_queue.s"

