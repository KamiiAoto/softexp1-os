***************************************************************
* test_step3.s : Step 3 UART1 送信割り込みテスト
*
* 目的:
*   UART1 の「送信可能」割り込みが起きるたびに 'a' を送信する。
*   成功時は PC の画面に aaaaa... が連続して表示される。
*
* アセンブル:
*   m68k-as -t 400 test_step3.s
*
* 注意:
*   このファイルは単独テスト用。os_defs.s と同じ場所に置く。
*   os_init.s / os_interface.s の処理は読み込まない。
***************************************************************

* UART1 や割り込みコントローラなどのレジスタ名とアドレスを定義する。
* 例: UTX1 は UART1 の送信レジスタ、IMR は割り込みマスクレジスタ。
.include "os_defs.s"


***************************************************************
* 1. スタック領域の確保
***************************************************************

* .bss は初期値を持たないデータを置く領域。
* .even は配置先を偶数番地にそろえる指定。

.section .bss
.even

SYS_STK:
    .ds.b 0x4000              | 0x4000 = 16384 バイト(16 KiB)を確保

.even
SYS_STK_TOP:                  | 確保したスタック領域の末尾を表すラベル

* 68000 のスタックは基本的にアドレスが小さくなる方向に伸びる。
* このため、初期スタックポインタには領域の末尾を設定する。


***************************************************************
* 2. CPU と周辺装置の初期化
***************************************************************

* .text は CPU が実行する命令を配置する領域。

.section .text
.even

boot:
    * CPUをスーパーバイザモードにする。
    * 割り込みマスクレベルを7に設定し、初期化中の割り込みを禁止する。
    move.w #0x2700, %SR

    * スタックポインタにSYS_STK_TOPのアドレスを設定する。
    * 割り込み発生時にPCやSRを保存できるようにする。
    lea.l SYS_STK_TOP, %SP


    ***********************************************************
    * 2-1. 割り込みベクタの設定
    ***********************************************************

    * UART1の割り込みレベルは4。
    * IVRの基準値を0x40とするので、
    *
    * 割り込みベクタ番号 = 0x40 + 4 = 0x44
    *
    * 68000では割り込みベクタ1つにつき4バイトなので、
    *
    * ベクタ格納アドレス = 0x44 * 4 = 0x110
    *
    * アドレス0x110にSEND_TESTの開始アドレスを書き込む。
    * これにより、UART1の割り込み発生時にSEND_TESTへ移動できる。

    move.l #SEND_TEST, 0x110


    ***********************************************************
    * 2-2. 割り込みコントローラの初期化
    ***********************************************************

    * IVRは割り込みベクタレジスタ。
    * 割り込みベクタ番号の基準値を0x40に設定する。
    move.b #0x40, IVR

    * IMRは割り込みマスクレジスタ。
    * 初期化中に割り込みが発生しないようにマスクする。
    move.l #0x00ffffff, IMR


    ***********************************************************
    * 2-3. UART1の初期化
    ***********************************************************

    * UART1の制御設定をリセットする。
    move.w #0x0000, USTCNT1

    * UART1の送受信機能を有効にする。
    *
    * 0xE104の設定では、
    * bit2 (TXEE) = 1 : 送信割り込みを許可
    * bit3 (RXRE) = 0 : 受信割り込みを禁止
    *
    * Step2では0xE108を使用したが、
    * Step3では送信割り込みだけを使用するため0xE104に変更する。
    move.w #0xe104, USTCNT1

    * UART1の通信速度を設定する。
    * Step1およびStep2で動作確認できた設定値を使用する。
    move.w #0x0038, UBAUD1


    ***********************************************************
    * 2-4. タイマ1の初期化
    ***********************************************************

    * タイマ1を停止状態に設定する。
    * Step3ではタイマを使用しないため、割り込みも発生させない。
    move.w #0x0004, TCTL1


    ***********************************************************
    * 2-5. UART1の割り込みを許可する
    ***********************************************************

    * IMRは周辺装置ごとの割り込みの許可・禁止を制御する。
    *
    * 0x00ff3ffbはUART1の割り込みを許可する設定値。
    * タイマ1など、今回使用しない割り込みはマスクしておく。
    *
    * ここまでで割り込み処理ルーチンやUARTの初期化は完了している。
    move.l #0x00ff3ffb, IMR

    * CPUの割り込みマスクレベルを0にする。
    *
    * 0x2000は、
    *   スーパーバイザモード
    *   割り込みマスクレベル0
    * を意味する。
    *
    * UART1の割り込みレベルは4なので、
    * CPUがUART1の割り込みを受け付けられるようになる。
    move.w #0x2000, %SR

    * 初期化が終了したのでMAINに移動する。
    bra MAIN


***************************************************************
* 3. メインループ
***************************************************************

* Step3では、MAIN自身は文字の送信を行わない。
*
* UART1から送信割り込みが発生したときだけ、
* SEND_TESTが呼び出され、文字'a'が送信される。
*
* そのため、MAINでは何もせず無限ループを行う。

MAIN:
    bra MAIN


***************************************************************
* 4. UART1 送信割り込み処理ルーチン
***************************************************************

* UART1の送信バッファが空になり、
* 次の文字を送信できる状態になると送信割り込みが発生する。
*
* CPUはベクタ番号0x44に対応するアドレス0x110を参照し、
* 登録されているSEND_TESTを実行する。

SEND_TEST:

    * UART1の送信レジスタUTX1に文字'a'を書き込む。
    *
    * 'a'のASCIIコードは0x61。
    *
    * 0x0800はフロー制御でCTSを無視するための制御ビット。
    *
    * したがって、
    * 0x0800 + 0x0061 = 0x0861
    *
    * をUTX1に書き込むことで、文字'a'が送信される。
    move.w #0x0800+'a', UTX1

    * 割り込み処理を終了する。
    *
    * rteはReturn from Exceptionの略。
    * スタックに保存されていたPCとSRを復元し、
    * 割り込み前のプログラムに戻る。
    rte


***************************************************************
* 5. なぜ文字'a'が連続して出力されるのか？
***************************************************************

* (1) UART1が送信可能になる。
*               ↓
* (2) UART1がCPUに送信割り込みを要求する。
*               ↓
* (3) CPUがSEND_TESTを実行する。
*               ↓
* (4) UTX1に文字'a'を書き込む。
*               ↓
* (5) UART1から文字'a'が送信される。
*               ↓
* (6) UART1が再び送信可能になる。
*               ↓
* (7) 再び送信割り込みが発生する。
*
* この処理を繰り返すため、
* PCの画面には文字'a'が連続して表示される。
*
* なお、このルーチンではD0などの汎用レジスタを変更しないため、
* Step2のようなD0の保存・復元は必要ない。


***************************************************************
* 6. 動作確認と終了方法
***************************************************************

* 【成功条件】
*
* キーボードから文字を入力しなくても、
* PCの画面に文字'a'が連続して表示されること。
*
* 表示例:
* aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa...
*
*
* 【正常な終了方法】
*
* 1. CPUボードのRESETボタンを押す。
*    → Step3のプログラムが停止し、連続送信が止まる。
*
* 2. m68k-termでCtrl+\を押して離し、続けてcを押す。
*    → Kermitのコマンドモードに戻る。
*
* 3. kermit>でqを入力してEnterを押す。
*    → 通常のターミナルに戻る。
*
* 4. プロンプトに$が表示されたことを確認する。
*
* ※ Ctrl+Zで終了しないこと。
*    プロセスが停止状態で残り、通信ポートがロックされる
*    原因になる。
***************************************************************
